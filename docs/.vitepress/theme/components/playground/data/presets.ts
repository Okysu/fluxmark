export function getPlaygroundPresets(locale: PlaygroundLocale): PlaygroundPreset[] {
  return presets[locale];
}

export function getDefaultPreset(locale: PlaygroundLocale): PlaygroundPreset {
  const first = presets[locale][0];
  if (first === undefined) throw new Error('Playground requires at least one preset.');
  return first;
}
